def main():
    draft = json.load(open(os.path.join(HERE, "shot-manifest.draft.json"), encoding="utf-8"))
    scene_of, vis_of, mas_of = {}, {}, {}
    for k, (ids, vis, mas) in enumerate(SCENES, 1):
        img = f"img{k:02d}"
        for sid in ids:
            scene_of[sid], vis_of[sid], mas_of[sid] = img, vis, mas
    miss = [s["id"] for s in draft if s["id"] not in scene_of]
    if miss:
        raise SystemExit(f"ยังไม่จัดฉาก: {miss}")
    # ตรวจ shot ที่อ้างใน SCENES แต่ไม่มีใน draft
    ids_draft = {s["id"] for s in draft}
    extra = [sid for sid in scene_of if sid not in ids_draft]
    if extra:
        raise SystemExit(f"อ้าง shot ที่ไม่มีในบท: {extra}")
    out = []
    for s in draft:
        sid = s["id"]
        p = PUNCH.get(sid)
        out.append({"id": sid, "act": s["act"], "start": s["start"], "end": s["end"],
                    "dur": s["dur"], "text": s["text"], "scene": scene_of[sid],
                    "visual": vis_of[sid], "type": TYPES.get(sid, "static"),
                    "caption": None if p else CAP.get(sid), "mascot": mas_of[sid],
                    "punch": {"word": p[0], "trigger": p[1], "effect": p[2], "color": p[3]} if p else None})
    json.dump(out, open(os.path.join(HERE, "shot-manifest.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    nimg = len(SCENES); ncap = sum(1 for x in out if x["caption"]); npu = sum(1 for x in out if x["punch"])
    print(f"ช็อต {len(out)} | ภาพ {nimg} | caption {ncap} + punch {npu} = {ncap+npu} ({100*(ncap+npu)//len(out)}%)")
    for sid,(w,tr,_,_) in PUNCH.items():
        t=[x for x in out if x["id"]==sid][0]["text"]
        if _norm(tr) not in _norm(t): print(f"  ⚠️ punch {sid}: trigger '{tr}' ไม่อยู่ในบท")


if __name__ == "__main__":
    main()

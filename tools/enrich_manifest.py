def main():
    draft = json.load(open(os.path.join(APDIR, "shot-manifest.draft.json"), encoding="utf-8"))
    scene_of, visual_of, mascot_of = {}, {}, {}
    for img, ids, visual, mascot in SCENES:
        for sid in ids:
            scene_of[sid] = img
            visual_of[sid] = visual
            mascot_of[sid] = mascot

    missing = [s["id"] for s in draft if s["id"] not in scene_of]
    if missing:
        raise SystemExit(f"ช็อตยังไม่ได้จัดฉาก: {missing}")

    out = []
    for s in draft:
        sid = s["id"]
        out.append({
            "id": sid, "act": s["act"],
            "start": s["start"], "end": s["end"], "dur": s["dur"],
            "text": s["text"],
            "scene": scene_of[sid],           # ช็อตที่ scene เดียวกัน = ใช้ภาพ Qwen ใบเดียว
            "visual": visual_of[sid],         # เนื้อภาพ (ไปเป็น prompt ต่อ)
            "type": TYPES.get(sid, "static"),
            "caption": CAPTIONS.get(sid),
            "mascot": mascot_of[sid],
        })
    json.dump(out, open(os.path.join(APDIR, "shot-manifest.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)

    n_img = len(SCENES)
    n_cap = sum(1 for s in out if s["caption"])
    n_static = sum(1 for s in out if s["type"] == "static")
    print(f"ช็อต {len(out)} | ภาพ Qwen {n_img} ใบ | caption {n_cap} ({100*n_cap//len(out)}%) | static {n_static} ({100*n_static//len(out)}%)")
    # เช็คภาพร่วมต้องเป็นช็อตติดกันเท่านั้น
    from itertools import groupby
    order = [s["scene"] for s in out]
    seen = set()
    for k, _ in groupby(order):
        if k in seen:
            print(f"  ⚠️ ภาพ {k} ใช้ในช็อตไม่ติดกัน")
        seen.add(k)
    print("เขียน: shot-manifest.json")


if __name__ == "__main__":
    main()
